"""Repair: the rung that makes this system usable.

Blocking destroys utility and trains users to route around the guardrail.
Repair preserves the answer and removes only the dangerous part -- redact the
identifier, drop the invented sentence, soften the over-generalisation, add the
caveat. This is what "correction preserves utility where blocking destroys it"
looks like in code.
"""
from __future__ import annotations

import re

from ..check.privacy import PATTERNS
from ..schemas import Completion, RiskVector

_SENT = re.compile(r"(?<=[.!?])\s+")


def redact_pii(text: str) -> tuple[str, int]:
    n = 0
    for kind, pat in PATTERNS.items():
        text, k = pat.subn(f"[REDACTED:{kind.upper()}]", text)
        n += k
    return text, n


def strip_unsupported(text: str, rv: RiskVector) -> tuple[str, list[str]]:
    """Surgical removal: drop ONLY the sentences the grounding check actually
    marked unsupported or uncovered, keeping everything else.

    This is why REPAIR beats BLOCK on utility -- the user still gets their
    answer, minus the invented part.
    """
    claims: list[str] = []
    for s in rv.signals:
        if s.detector == "grounding":
            claims = [
                c["claim"]
                for c in s.evidence.get("claims", [])
                if c.get("status") in ("unsupported", "not_covered")
            ]
    if not claims:
        return text, []

    removed, kept = [], []
    for sent in _SENT.split(text):
        stripped = sent.strip()
        if any(stripped[:80] in c or c[:60] in sent for c in claims):
            removed.append(stripped)
        else:
            kept.append(sent)

    out = " ".join(kept).strip() or "I don't have verified information on that."
    return out, removed


def hedge(text: str, rv: RiskVector) -> str:
    if rv.per_dim.get("hallucination", 0) > 0.4 or rv.abstained:
        return (
            text
            + "\n\n_Note: parts of this could not be verified against an approved "
            "source. Please confirm before acting on it._"
        )
    return text


def auto_repair(
    comp: Completion, rv: RiskVector, disclosure: bool = False
) -> tuple[str, list[str]]:
    """Returns (repaired_text, human-readable notes).

    The notes are not cosmetic: they are the user-facing explanation AND the
    audit record of what was changed and why.
    """
    notes: list[str] = []
    text = comp.text

    text, n = redact_pii(text)
    if n:
        notes.append(f"redacted {n} personal-data span(s)")

    text, removed = strip_unsupported(text, rv)
    if removed:
        notes.append(f"removed {len(removed)} unverified claim(s)")

    if rv.per_dim.get("bias", 0) > 0.4:
        text = re.sub(
            r"\b(all|always|never|typically|usually|tend to)\b",
            "in some cases",
            text,
            flags=re.I,
        )
        notes.append("softened over-generalising language")

    text = hedge(text, rv)

    if disclosure:
        text += (
            "\n\n_This response was generated by an AI system and screened "
            "automatically before delivery._"
        )
        notes.append("added AI disclosure (EU overlay)")

    return text, notes
